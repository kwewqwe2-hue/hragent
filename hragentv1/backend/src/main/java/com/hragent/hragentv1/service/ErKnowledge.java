    public Optional<Guide> match(String text) {
        String key = has(text,"竞业","保密协议") ? "noncompete" : has(text,"工伤","工作受伤") ? "injury"
            : has(text,"调岗","调薪","降薪") ? "change" : has(text,"投诉","申诉","举报","霸凌","骚扰","劳动仲裁","集体维权") ? "complaint"
            : has(text,"焦虑","倦怠","压力","心理","失眠","抑郁","eap","好累","难过","情绪","热线") ? "care"
            : has(text,"离职","辞职","交接","离职访谈") ? "offboarding" : has(text,"黑话","对齐","闭环","权限","协作工具") ? "culture"
            : has(text,"新人","入职导航","第一周","第一个月","入职指引","入职当天") ? "onboarding" : "";
        return guides.stream().filter(g -> g.key().equals(key)).findFirst();
    }
