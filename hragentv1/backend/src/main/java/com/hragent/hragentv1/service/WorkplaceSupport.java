package com.hragent.hragentv1.service;

import java.util.Optional;
import java.util.regex.Pattern;

/** Practical, non-diagnostic support, before document retrieval. No employee profiling or storage. */
public final class WorkplaceSupport {
    private WorkplaceSupport() { }
    private static boolean has(String s,String... words){for(String w:words)if(s.contains(w))return true;return false;}
    public static String intent(String message) {
        String q=ErSafety.normalize(message);
        if(q.isBlank())return "NONE";
        boolean feeling=has(q,"焦虑","难过","委屈","烦躁","紧张","害怕","很累","太累","疲惫","压力大","压力很大","睡不着","失眠","不开心","心情不好","难受","内耗","迷茫","孤独","没人理解","情绪低落","不想上班","没动力","没精神","倦怠","喘不过气","不舒服","抑郁");
        feeling=feeling||Pattern.compile("压力.{0,4}(大|重)|心情.{0,3}(差|低落)|工作.{0,3}(好累|好烦)").matcher(q).find();
        boolean policy=has(q,"制度","政策","条文","标准","规定","几天","多少钱","报销","审批权限");
        if(policy&&!feeling)return "NONE";
        if(java.util.Set.of("我想休息","我想休息一下","想休息","我需要休息","我想歇一会","想歇一会").contains(q))return "REST";
        if(has(q,"今天很开心","好开心","很高兴","终于做到了","很有成就感"))return "POSITIVE";
        if(has(q,"只想倾诉","只想说说","不想听建议","先听我说","别给建议","陪我聊","想找人聊","想找个人聊"))return "LISTEN";
        if(has(q,"他不同意","她不同意","不接受我的建议","沟通了没用","说了也没用","被拒绝了"))return "PUSHBACK";
        if(has(q,"睡不着","失眠","睡不好"))return "SLEEP";
        if(has(q,"被批评","批评我","挨批","被否定","否定我","被骂","做错","犯错","自责","觉得自己很差","觉得自己很笨","能力不行"))return "CRITICISM";
        boolean talk=has(q,"沟通","开口","表达","商量","拒绝","怎么说","不敢说","争取","谈谈","谈一谈","协调","不理解我");
        if(talk&&has(q,"主管","领导","经理","老板","工作安排","任务安排","优先级"))return "MANAGER";
        if(has(q,"怎么安排工作","如何安排工作","工作怎么安排","规划工作","安排任务","安排时间"))return "PLANNING";
        if(has(q,"做不完","忙不过来","任务太多","事情太多","工作太多","工作量大","工作量太大","加班很累","一直加班","天天加班","安排不过来"))return "WORKLOAD";
        if(has(q,"同事","团队")&&has(q,"相处","矛盾","冲突","误会","沟通","排斥","孤立","不理我","合作不顺"))return "CONFLICT";
        if(has(q,"新人","刚入职","刚加入","新工作")&&has(q,"适应","融入","紧张","担心","害怕","不熟","无所适从"))return "ADJUSTMENT";
        if(has(q,"倦怠","没动力","没精神","不想上班","疲惫","很累","太累"))return "BURNOUT";
        if(feeling||has(q,"情绪疏导","心理疏导","缓解压力","调节情绪","心理支持","情绪支持","安慰我"))return "EMOTION";
        return "NONE";
    }
    public static Optional<String> reply(String message) {
        String q=ErSafety.normalize(message), kind=intent(message);
        String answer=switch(kind) {
            case "REST" -> "可以，先照顾好自己的状态。你想先歇几分钟缓一缓，还是想安排一段请假休息？我们可以一起把下一步理清。";
            case "POSITIVE" -> "听起来今天有让你开心、觉得有收获的事。可以给自己一点时间享受这个时刻，也记下哪些做法或支持对你有帮助。愿意说说发生了什么吗？";
            case "PLANNING" -> "可以先把目标、时间和依赖关系理清，再安排每天要做的事。\n\n先列出任务、截止时间和完成标准，标出必须等别人提供信息的部分；再选出今天最重要的一两件，为临时事项留一点余量。\n\n如果几项任务期限冲突，和负责人确认先后顺序或缩小交付范围，不必默默承诺全部按时完成。一天结束时简短复盘，再调整明天的计划。\n\n你现在是想安排每天的工作，还是有几项任务同时到期？";
            case "MANAGER" -> "和主管谈工作安排，可以先把任务和取舍说清楚，让对方容易做决定。如果你担心开口会被理解成推卸责任，可以把重点放在交付目标上。\n\n"
                +"1. 会前列出手头任务、截止时间、预计还要多久，以及卡住的地方，先挑最需要确认的两三件。\n"
                +"2. 约一个短时间私下沟通，说明事实和影响，再请主管确认优先级、交付范围或可用支持。\n"
                +"3. 给出两个可选安排，沟通后用简短消息确认共识；如果又增加任务，再确认哪一项可以延后。\n\n"
                +"可以这样说：\n“我想和您确认一下这周的优先级。目前A和B都要求周五交付，按现有工作量，两项同时完成可能影响质量。您更希望我先保证哪一项？另一项能否调整时间、缩小范围，或请同事协助？我会按确认的安排推进。”\n\n"
                +"你现在更难的是任务太多、优先级不清楚，还是担心主管的反应？";
            case "WORKLOAD" -> "事情做不完时，很容易一边着急，一边觉得是自己不够努力。先把工作量和可用时间分开看，不必把所有冲突都自己扛下来。\n\n"
                +"先做一个小整理：把任务分成今天必须交、可以协商、需要别人支持三类，每项写上预计耗时。选出今天最重要的一项，先完成一个能交付的小部分。\n\n"
                +"接着向负责人确认取舍：“我今天能完成A；如果B也必须今天交，需要减少A的范围或增加支持。您希望怎么排？”临时新增任务时，也请对方重新确认顺序。\n\n"
                +"如果这种超负荷持续发生，可以记录任务和实际耗时，再讨论分工或工作量调整。现在压得你最重的是哪件事，它什么时候必须完成？";
            case "PUSHBACK" -> "如果你是说，对方没有接受你提出的调整，可以先弄清他最在意的限制，再谈一个更小的可行方案。一次没谈成不代表你表达得不好。\n\n"
                +"可以追问：“您最不能调整的是截止时间、交付范围，还是人员安排？”然后选一个能动的部分，例如先交核心内容、分阶段提交，或约一次中途检查。\n\n"
                +"可以这样回应：“我理解时间不能改。那我先完成最关键的部分，剩下的分阶段补齐，您看可以吗？如果都需要完整交付，我还需要哪些支持？”\n\n"
                +"若存在明显权力压力，优先选安全的沟通方式，必要时请可信任的同事、导师或HR协助。对方当时具体是怎么回应的？";
            case "CONFLICT" -> "和同事合作不顺，会让工作本身之外又多一份消耗。可以先不判断对方的动机，选一件具体发生的事来谈。\n\n"
                +"找双方都比较平静、方便说话的时候，用“发生了什么—对工作的影响—希望怎样配合”来表达，再听听对方的理解。\n\n"
                +"例如：“昨天安排变更时我没有及时收到消息，导致我重复做了一部分工作。以后变更能否在群里同步一下？你这边有什么困难，也可以一起调整。”\n\n"
                +"先约定一个小变化，过几天再看看有没有改善。如果直接沟通让你感到不安全，可以先请可信任的人协助。最近哪件事最让你不舒服？";
            case "CRITICISM" -> "被批评或发现自己做错事，可能会让人委屈、紧张，甚至开始否定自己。先给自己一点缓冲：一次反馈或失误，不能概括你的全部能力。\n\n"
                +"等情绪稍微平稳，把反馈分成两部分：哪些是可以核对的事实，哪些是评价或不恰当的表达。对事实，选一个最能改进的小步骤；对含糊的评价，可以请对方给具体例子和期待。\n\n"
                +"可以这样说：“我想把这件事改好，能否指出最需要调整的地方，以及您期望的完成标准？我先改这一项，再请您确认。”\n\n"
                +"如果伴随当众羞辱或持续贬低，你可以先寻找支持，而不是独自承受。你更难受的是事情本身，还是对方表达的方式？";
            case "ADJUSTMENT" -> "刚进入新环境，需要同时适应人、流程和工作期待，感到紧张并不说明你不适合这里。可以先把目标缩小到“今天弄清一件事”。\n\n"
                +"先列出最影响当前任务的三个疑问，找导师或一位容易沟通的同事确认。再和主管约一次简短沟通，明确第一周最重要的交付、完成标准，以及遇到问题可以找谁。\n\n"
                +"可以这样开口：“我想尽快熟悉团队，您建议我这周优先掌握哪两件事？如果我卡住了，向谁请教比较合适？”\n\n"
                +"每天记下一个已经弄清或完成的小进展，给自己一点适应空间。你目前最不熟悉的是工作内容、流程，还是和大家相处？";
            case "SLEEP" -> "睡不好又要应付工作，确实会更难熬。今晚可以先把目标放在让自己安稳一些，不要求自己立刻把所有烦心事解决。\n\n"
                +"睡前把反复惦记的事情写下来，每件只留一个明天可以处理的步骤，然后暂时放下工作消息。做一点温和、让你舒服的放松活动；如果关注呼吸反而更紧张，就把注意力放在脚踩地面的感觉和眼前的物品上。\n\n"
                +"如果睡眠问题持续、加重，或明显影响白天生活，可以联系专业人员评估，别自行依赖药物解决。你是入睡困难、容易醒，还是醒来后还觉得很累？";
            case "BURNOUT" -> "一直疲惫、提不起劲时，单靠要求自己再坚持，可能只会更累。可以先看看哪些消耗来自工作安排，哪些支持目前缺着。\n\n"
                +"今天先做一件能减少负担的小事：暂停一项非紧急任务、安排一次真正离开工作的休息，或请人分担一个具体环节。再把持续消耗你的两三件事记录下来，和负责人讨论任务量、分工或恢复时间。\n\n"
                +"如果这种状态持续，连平时喜欢的活动也难以投入，或明显影响生活，可以寻求专业支持。不能仅凭这段话判断是倦怠还是其他原因。现在最消耗你的是工作量、人际关系，还是看不到工作的意义？";
            case "LISTEN" -> "可以，我们先不急着找办法。你只需要讲愿意讲的部分，不必把事情组织得很完整。\n\n你现在最想说的是发生了什么，还是这件事让你有什么感受？";
            case "EMOTION" -> "听起来你现在并不好受。可以先不急着把情绪压下去，我们先照顾此刻，再把事情拆小。\n\n"
                +"如果愿意，先停一小会儿，感受双脚踩在地面上，看看周围几样物品；呼吸保持自然，任何让你不舒服的练习都可以停止。\n\n"
                +"接着试着给感受取个名字：是担心、委屈、愤怒，还是疲惫？把正在发生的事实和最担心的结果分开，选一件今天能影响的小事，或联系一个愿意听你说的人。\n\n"
                +"如果这样的困扰持续、加重或影响生活，专业支持也可以成为一个选择。你愿意从最近最让你难受的一件事说起吗？";
            default -> null;
        };
        if(answer!=null&&has(q,"抑郁","诊断","用药","吃什么药"))answer+="\n\n仅凭聊天不能判断你是否患有心理疾病，也不能决定用药；可以请有资质的专业人员进一步评估。";
        if(answer!=null&&has(q,"焦虑","害怕","紧张","委屈")&&has(kind,"MANAGER","WORKLOAD","CONFLICT"))
            answer="带着这样的感受去沟通，可能会有些难。可以先写下想说的话，等自己稍微平稳，再选择安全、合适的方式开口。\n\n"+answer;
        return Optional.ofNullable(answer);
    }
    public static boolean emotional(String message) {return java.util.Set.of("EMOTION","SLEEP","BURNOUT").contains(intent(message));}
}
