const assert = require('node:assert/strict')
const {chromium} = require(process.env.USERPROFILE + '/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
;(async () => {
 const browser = await chromium.launch({channel:'msedge',headless:true})
 try {
  const page = await browser.newPage(); const errors=[]; const ids=new Set()
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://localhost:5174/')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.locator('.quick-board-handle').waitFor()
  for (const [title,expected] of [['今日人事提醒','提醒'],['入职第一天','账号'],['制度速读','休假与考勤'],['请假前检查','起止日期']]) {
   await page.locator('.quick-board-handle').dblclick()
   const request=page.waitForRequest(r=>r.url().endsWith('/web-chat/messages'))
   await page.getByRole('button',{name:title,exact:true}).click()
   const id=(await request).postDataJSON().conversationId; assert.ok(id); assert.ok(!ids.has(id)); ids.add(id)
   await page.waitForFunction(()=>!document.querySelector('textarea').disabled)
   assert.match(await page.locator('.message-row.assistant .markdown-content').innerText(),new RegExp(expected))
   await page.locator('textarea').fill('我还有多少年假')
   const followup=page.waitForRequest(r=>r.url().endsWith('/web-chat/messages'))
   await page.getByRole('button',{name:'发送',exact:true}).click()
   assert.equal((await followup).postDataJSON().conversationId,id)
   await page.waitForFunction(()=>!document.querySelector('textarea').disabled)
   assert.match(await page.locator('.message-row.assistant .markdown-content').last().innerText(),/年假.*(天|额度)/)
  }
  let release; const hold=new Promise(resolve=>release=resolve)
  await page.route('**/web-chat/messages',async route=>{const response=await route.fetch();await hold;await route.fulfill({response})})
  await page.locator('textarea').fill('你好');await page.getByRole('button',{name:'发送',exact:true}).click()
  await page.locator('.quick-board-handle').dblclick()
  const count=await page.locator('.conversation-item').count()
  assert.equal(await page.locator('.quick-board-actions').getByRole('button',{name:'今日人事提醒',exact:true}).isDisabled(),true)
  await page.locator('.quick-board-actions').getByRole('button',{name:'今日人事提醒',exact:true}).evaluate(button=>button.click())
  assert.equal(await page.locator('.conversation-item').count(),count)
  release();await page.waitForFunction(()=>!document.querySelector('textarea').disabled)
  assert.equal(await page.locator('.quick-board-actions').getByRole('button',{name:'今日人事提醒',exact:true}).isEnabled(),true)
  await page.reload();await page.locator('.message-row.assistant').first().waitFor()
  assert.equal(await page.locator('.conversation-item').count(),count)
  assert.deepEqual(errors,[])
  console.log('PASS: all four Kaka shortcuts, independent conversation IDs, personal follow-ups, busy-click protection, reload persistence, no JS errors')
 } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})

