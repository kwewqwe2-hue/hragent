const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const playwright = require(process.env.PLAYWRIGHT_PACKAGE || path.join(process.env.USERPROFILE || '', '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'))
;(async () => {
  const output = path.resolve(__dirname, '../.artifacts/employee-services')
  await fs.mkdir(output, { recursive: true })
  const browser = await playwright.chromium.launch({ headless: true, channel: 'msedge' })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    await page.goto('http://localhost:5174')
    await page.getByRole('button', { name: '登录', exact: true }).click()
    await page.getByRole('button', { name: '员工服务 · 自助办理', exact: true }).waitFor()
    await page.getByRole('textbox', { name: '' }).last().fill('我还有几天年假')
    await page.getByRole('button', { name: '发送', exact: true }).click()
    await page.locator('.message-row.assistant .markdown-content').filter({ hasText: '台账' }).waitFor()
    await page.getByRole('button', { name: '员工服务 · 自助办理', exact: true }).click()
    await page.getByRole('heading', { name: '与你相关的制度，带着依据回答。' }).waitFor()
    await page.getByRole('button', { name: '考勤打卡规定', exact: true }).click()
    await page.locator('.es-policy-result').waitFor()
    await page.screenshot({ path: path.join(output, 'employee-services-desktop.png'), fullPage: true })
    await page.getByRole('button', { name: '证明办理', exact: true }).click()
    await page.getByText('我的申请', { exact: true }).waitFor()
    await page.getByRole('button', { name: '办事清单', exact: true }).click()
    await page.getByPlaceholder('例如：北京', { exact: true }).fill('北京')
    await page.getByPlaceholder('例如：上海', { exact: true }).fill('上海')
    await page.getByRole('button', { name: '生成准备清单', exact: true }).click()
    await page.getByRole('button', { name: '下载清单', exact: true }).waitFor()
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: '下载清单', exact: true }).click()
    const download = await downloadPromise; await download.saveAs(path.join(output, 'browser-checklist.md'))
    await page.getByRole('button', { name: /提醒与待办/ }).click()
    await page.getByRole('button', { name: '导出日历', exact: true }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: path.join(output, 'employee-services-mobile.png'), fullPage: true })
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)
    assert.equal(overflow, false, 'Mobile layout overflows viewport')
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.goto('http://localhost:5173/login')
    const inputs = page.locator('input')
    await inputs.nth(0).fill('zhangsan'); await inputs.nth(1).fill('123456')
    await page.getByRole('button', { name: '登录', exact: true }).click()
    await page.waitForURL(url => !url.pathname.includes('login'))
    await page.goto('http://localhost:5173/employee-services')
    await page.getByRole('heading', { name: '与你相关的制度，带着依据回答。' }).waitFor()
    await page.screenshot({ path: path.join(output, 'saas-employee-services.png'), fullPage: true })
    const adminPage = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
    adminPage.on('pageerror', error => errors.push(error.message))
    await adminPage.goto('http://localhost:5174/?view=services')
    await adminPage.getByLabel('账号', { exact: true }).fill('wanghr')
    await adminPage.getByLabel('密码', { exact: true }).fill('123456')
    await adminPage.getByRole('button', { name: '登录', exact: true }).click()
    await adminPage.getByRole('button', { name: 'HR 维护', exact: true }).click()
    const picker = adminPage.locator('.es-employee-picker select')
    await picker.locator('option').nth(1).waitFor({ state: 'attached' })
    const firstEmployee = await picker.locator('option').nth(1).getAttribute('value')
    await picker.selectOption(firstEmployee)
    await adminPage.getByRole('button', { name: '保存服务档案', exact: true }).waitFor()
    await adminPage.screenshot({ path: path.join(output, 'hr-service-settings.png'), fullPage: true })
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({ passed: true, checks: ['chat balance response', 'policy lookup', 'certificate list', 'checklist form and download', 'reminders', 'mobile width', 'SaaS entry', 'HR profile form', 'no JS errors'] }))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
